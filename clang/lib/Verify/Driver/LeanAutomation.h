/// CppVerify/Auto.lean, written with every export. Its steps were chosen by
/// what proves the goals of the test suite (heap stores as the functions
/// they define, machine arithmetic as integers, then grind; stating toInt
/// ranges and removing Int.bmod first proved nothing more, the latter less),
/// each with a heartbeat budget of its own, as Vermilion's discharger ladder.
inline constexpr llvm::StringLiteral LeanAutomationSource =
    R"lean(/- Generated by CppVerify: the tactics of its automatic proofs, which proof
   files may use too. Regeneration replaces this file. -/
import Lean
import CppVerify.Prelude

register_option cppverify.autoBudget : Nat := {
  defValue := 50000
  descr := "the heartbeats, in thousands, each step of cppverify_auto may take"
}

register_option cppverify.autoReport : String := {
  defValue := ""
  descr := "a file to which cppverify_auto adds the step that proves each goal"
}

namespace CppVerify.Auto
open Lean Elab Tactic Meta

/-- Adds a line to a report, written at once: a process stopped later keeps
it. -/
def report (file line : String) : IO Unit := do
  let handle ← IO.FS.Handle.mk file .append
  handle.putStrLn line
  handle.flush

/-- Whether a proof depends on no axiom but Lean's foundations: a step that
proves a goal with a lemma the user has not proved is no proof. -/
def foundational (proof : Expr) : MetaM Bool := do
  for c in proof.getUsedConstants do
    let axioms ← try collectAxioms c catch _ => return false
    for a in axioms do
      unless a == ``propext || a == ``Quot.sound || a == ``Classical.choice do
        return false
  return true

end CppVerify.Auto

open Lean Elab Command in
/-- Reports the axioms a theorem depends on, or that the environment has no
such theorem (the kernel rejected it). -/
elab "#cppverify_axioms " file:str name:ident : command => do
  let name := name.getId
  let line ← liftCoreM do
    if (← getEnv).contains name then
      let axioms ← collectAxioms name
      pure s!"axioms\t{name}\t{",".intercalate (axioms.toList.map toString)}"
    else
      pure s!"axioms\t{name}\tmissing"
  CppVerify.Auto.report file.getString line

open Lean Elab Tactic Meta in
/-- Unfolds a goal that is still a readable form, as one without binders is
after `apply G.of_readable`. -/
elab "cppverify_unfold_readable" : tactic => withMainContext do
  let target ← getMainTarget
  if let .const name _ := target.getAppFn then
    if name.isStr && name.getString! == "readable" then
      let unfolded ← deltaExpand target (· == name)
      replaceMainGoal [← (← getMainGoal).change unfolded]

/-- Machine comparisons, constants, and overflow conditions as facts about
integers. -/
macro "cppverify_norm" : tactic => `(tactic| (try simp only [cppBvSlt, cppBvSle,
  cppBvUlt, cppBvUle, BitVec.slt_iff_toInt_lt, BitVec.sle_iff_toInt_le,
  BitVec.ult_iff_lt, BitVec.ule_iff_le, BitVec.lt_def, BitVec.le_def,
  BitVec.toInt_ofInt, BitVec.signExtend_eq, BitVec.saddOverflow,
  BitVec.ssubOverflow, BitVec.smulOverflow, BitVec.negOverflow,
  BitVec.sdivOverflow, BitVec.uaddOverflow, BitVec.toInt_add, BitVec.toInt_sub,
  BitVec.toInt_mul, BitVec.toInt_neg, decide_eq_true_eq, decide_eq_false_iff_not,
  Bool.or_eq_true, Bool.and_eq_true, Bool.not_eq_true, Bool.or_eq_false_iff,
  Bool.and_eq_false_iff, ge_iff_le, gt_iff_lt, Nat.reducePow, Nat.reduceSub,
  Nat.reduceAdd, Nat.reduceMul] at *))

/-- Memory as values: each store is the function it defines. -/
macro "cppverify_heap" : tactic => `(tactic| (
    try simp only [heapStoreInt, heapStoreBool, heapStoreBv] at *
    try subst_vars
    try simp only [heapSelectInt, heapSelectBool, heapSelectBv] at *))

/-- The steps of `cppverify_auto`, cheapest first. -/
macro "cppverify_auto_grind" : tactic =>
  `(tactic| (cppverify_unfold_readable; grind))
macro "cppverify_auto_heap" : tactic => `(tactic| (
    cppverify_unfold_readable
    cppverify_heap
    cppverify_norm
    all_goals grind))
macro "cppverify_auto_bv" : tactic => `(tactic| (
    cppverify_unfold_readable
    cppverify_norm
    all_goals grind))
macro "cppverify_auto_decide" : tactic =>
  `(tactic| (cppverify_unfold_readable; decide))
macro "cppverify_auto_simp" : tactic =>
  `(tactic| (cppverify_unfold_readable; simp_all))

open Lean Elab Tactic in
/-- Tries each step on the goal, each with `cppverify.autoBudget` heartbeats
of its own, and keeps the first that proves it. A step that runs out of
heartbeats, leaves goals, or uses an axiom outside Lean's foundations counts
as failed and changes nothing. -/
elab "cppverify_auto" : tactic => do
  let options ← getOptions
  let goal ← getMainGoal
  let budget := cppverify.autoBudget.get options
  let steps : List (String × Syntax.Tactic) := [
    ("cppverify_auto_grind", ← `(tactic| cppverify_auto_grind)),
    ("cppverify_auto_heap", ← `(tactic| cppverify_auto_heap)),
    ("cppverify_auto_bv", ← `(tactic| cppverify_auto_bv)),
    ("cppverify_auto_decide", ← `(tactic| cppverify_auto_decide)),
    ("cppverify_auto_simp", ← `(tactic| cppverify_auto_simp))]
  for (name, step) in steps do
    let attempt : TacticM Unit := do
      let heartbeats ← IO.getNumHeartbeats
      withTheReader Core.Context
          (fun ctx => { ctx with initHeartbeats := heartbeats,
                                 maxHeartbeats := budget * 1000 }) do
        evalTactic step
        unless (← getUnsolvedGoals).isEmpty do
          throwError "{name} left goals"
        unless ← CppVerify.Auto.foundational (← instantiateMVars (.mvar goal)) do
          throwError "{name} used an axiom outside Lean's foundations"
    let saved ← saveState
    let proved ← tryCatchRuntimeEx (return (← tryTactic? attempt).isSome)
      fun _ => do saved.restore; return false
    if proved then
      let file := cppverify.autoReport.get options
      unless file.isEmpty do
        let decl := (← Term.getDeclName?).getD .anonymous
        CppVerify.Auto.report file s!"step\t{decl}\t{name}"
      return
  throwError "cppverify_auto did not prove the goal (tried {steps.map (·.1)})"
)lean";

